"""Rebuild the complete merged display after the real first10 usage withdrawal.

No model, private profile, historical score recomputation or source mutation.
All new native outputs must be denied by the changed whole-ledger binding.
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import sqlite3
import sys

ROOT = Path(__file__).resolve().parents[1]
BUILDER_SHA = 'fa18087cf809cf44168c513692075f9ae745d5a5bce9a694e3cee57343bf7473'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def check_unchanged(pins):
    if any(sha(path) != digest for path, digest in pins.items()):
        raise ValueError('Withdrawal source changed before publication')


def metadata_candidate(row):
    if row.get('features') or row.get('feature_provenance'):
        raise ValueError('Metadata loader returned content features')
    return {'work_id': row['work_id'], 'title': row['title'], 'authors': row['authors'],
        'display_title_aliases': [a['title'] if isinstance(a, dict) else a for a in row['display_title_aliases']],
        'read_status': row['read_status'], 'external_ids': row.get('external_ids', []),
        'features': {}, 'feature_provenance': {}}


def build(args):
    pins = {}
    def pin(path, expected=None):
        path = Path(path).resolve(strict=True)
        digest = sha(path)
        if expected is not None and digest != expected:
            raise ValueError('Pinned withdrawal component differs: '+path.name)
        pins[str(path)] = digest
        return path
    builder_path = pin(ROOT/'scripts/build_world_pilot_delivery_v1.py', BUILDER_SHA)
    module_spec = importlib.util.spec_from_file_location('pinned_world_pilot_builder', builder_path)
    builder = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(builder)
    prior = args.prior_delivery.resolve(strict=True)
    prior_manifest_path = pin(prior/'manifest.json')
    prior_manifest = json.loads(prior_manifest_path.read_bytes())
    if prior_manifest['adapter_sha256'] != BUILDER_SHA:
        raise ValueError('Prior full delivery was not generated by the pinned original builder')
    for name in ('delivery.json', 'index.html'):
        pin(prior/name, prior_manifest['output_sha256'][name])
    prior_delivery = json.loads((prior/'delivery.json').read_bytes())
    baseline = ROOT/'data/autonomous-next-v3/database/phase3-personal-poc-with-declared-genres-v2'
    baseline_manifest = json.loads(pin(baseline/'manifest.json', builder.BASELINE_MANIFEST_SHA).read_bytes())
    old = json.loads(pin(baseline/'delivery.json', builder.BASELINE_DELIVERY_SHA).read_bytes())
    if baseline_manifest['output_sha256']['delivery.json'] != builder.BASELINE_DELIVERY_SHA or len(old['ranking']) != 1989:
        raise ValueError('Original 1989-row baseline differs')
    runtime = args.runtime_root.resolve(strict=True)
    for relative in ('src/recommend_book/recommendation/personal_ranking.py',
                     'src/recommend_book/recommendation/personal_site.py',
                     'config/recommendation-label-display-ja.json'):
        expected = prior_manifest['source_sha256'][str(ROOT/relative)]
        pin(ROOT/relative, expected)
        pin(runtime/relative, expected)
    pin(__file__)
    pin(args.database)
    pin(args.selected_inputs)
    pin(args.ledger, args.ledger_sha256)
    output = args.output.resolve()
    if output.exists() or any(output.is_relative_to(protected) for protected in (prior, runtime, args.database.resolve().parent, baseline)):
        raise ValueError('Fresh separate withdrawal output required')
    sys.path.insert(0, str(runtime/'src'))
    from recommend_book.models import WorkInput
    from recommend_book.usage_guard_v4 import UsageGuard
    from recommend_book.next_database_v4 import load_next_world_database, get_next_inputs
    from recommend_book.recommendation.personal_ranking import rank_personal_features
    from recommend_book.recommendation.personal_site import render_personal_site
    works = [WorkInput.model_validate_json(line) for line in args.selected_inputs.read_bytes().splitlines() if line.strip()]
    selected = {w.work_id: w for w in works}
    originals = {w.work_id: w for w in get_next_inputs(args.database)['classification']}
    if len(selected) != 10 or len(works) != 10 or any(originals.get(key) != work for key, work in selected.items()):
        raise ValueError('Exact original first10 full WorkInputs required')
    old_by_id = {r['work_id']: r for r in old['ranking']}
    prior_by_id = {r['work_id']: r for r in prior_delivery['ranking']}
    if (len(prior_by_id) != 1999 or len(prior_delivery['ranking']) != 1999
        or set(prior_by_id)-set(old_by_id) != set(selected)
        or any(prior_by_id.get(key) != value for key, value in old_by_id.items())):
        raise ValueError('Prior complete view must contain unchanged baseline1989 plus exactly first10')
    connection = sqlite3.connect(args.database.resolve().as_uri()+'?mode=ro&immutable=1', uri=True)
    try:
        packets = [json.loads(row[0]) for row in connection.execute('SELECT packet_json FROM next_classification_derivations')]
    finally:
        connection.close()
    if len(packets) != 10 or {p['native_result']['work_id'] for p in packets} != set(selected):
        raise ValueError('Actual adopted first10 native packet coverage differs')
    guard = UsageGuard(args.ledger, expected_ledger_sha256=args.ledger_sha256)
    native_decisions = []
    with guard.native_scopes.validation():
        for packet in packets:
            for artifact in packet['source_manifest']['artifacts'].values():
                pin(artifact['path'], artifact['sha256'])
            decision = guard.check_derived(packet['native_result'], packet['originating_input_hashes'],
                'display', source_manifest=packet['source_manifest'])
            if decision.allowed:
                raise ValueError('Withdrawal requires every new native classification to be denied')
            native_decisions.append({'work_id': packet['native_result']['work_id'],
                'decision': decision.model_dump(mode='json')})
    metadata = load_next_world_database(args.database, guard=guard, usage='display', content_classified=False)
    content = load_next_world_database(args.database, guard=guard, usage='display', content_classified=True)
    if content['rows'] or content['audit']['feature_adopted_work_count']:
        raise ValueError('Revoked native content loader must admit no new rows or features')
    metadata_by_id = {row['work_id']: row for row in metadata['rows']}
    candidates, credits, decisions = [], {}, []
    for work in works:
        decision = guard.check_input(work, 'display')
        decisions.append({'work_id': work.work_id, 'decision': decision.model_dump(mode='json'),
            'metadata_projection_available': work.work_id in metadata_by_id})
        if not decision.allowed or work.work_id not in metadata_by_id:
            continue
        candidates.append(metadata_candidate(metadata_by_id[work.work_id]))
        credits[work.work_id] = builder.source_credits(work)
    ranking = rank_personal_features(candidates, [], limit=len(candidates))
    if any(r['content_labels'] or r['score'] is not None or r['explanations'] for r in ranking['ranking']):
        raise ValueError('Withdrawn new rows carried classification features or ranking evidence')
    if len(ranking['ranking']) != 9:
        raise ValueError('Actual one-work first10 withdrawal must leave nine authorized metadata rows')
    merged = builder.merge_rankings(old['ranking'], ranking['ranking'])
    delivery = {'version': 'personal-feature-ranking-v1', 'ranking': merged,
        'audit': dict(old['audit']) | {'input_candidates': len(merged), 'eligible_n': len(merged),
            'catalogue_candidate_n': len(merged),
            'catalogue_feature_bearing_n': sum(bool(row['content_labels']) for row in merged),
            'new_world_pilot_n': len(ranking['ranking']), 'new_world_pilot_feature_bearing_n': 0,
            'prior_rows_unchanged_n': 1989, 'private_profile_connection_n_this_rebuild': 0,
            'unknown_read_status_n': sum(row['read_status']=='unknown' for row in merged),
            'quality_verified': False, 'confidence_calibrated': False}}
    labels = json.loads((ROOT/'config/recommendation-label-display-ja.json').read_bytes())['labels']
    html = render_personal_site(delivery, labels).replace('<script id="recommendation-data"',
        builder.credit_html(credits)+'<script id="recommendation-data"', 1)
    omitted = sorted(set(selected)-set(credits))
    report = {'version': 'full-world-pilot-withdrawal-v1', 'merged_display_n': len(merged),
        'prior_merged_display_n': 1999, 'prior_rows_unchanged_n': 1989,
        'new_display_n': len(ranking['ranking']), 'new_feature_bearing_n': 0, 'new_supported_n': 0,
        'omitted_selected_work_ids': omitted, 'native_denied_n': len(native_decisions), 'native_allowed_n': 0,
        'new_ranking_audit': ranking['audit'], 'metadata_loader_audit': metadata['audit'],
        'content_loader_audit': content['audit'], 'whole_ledger_change_invalidated_all_new_native_results': True,
        'old_scores_unchanged': True, 'source_artifacts_unchanged': True,
        'private_profile_used': False, 'actual_model_calls': 0, 'quality_verified': False,
        'restoration': 'Use the original pinned prior delivery; this helper never modifies it.'}
    check_unchanged(pins)
    output.mkdir(parents=True)
    builder.save(output/'delivery.json', delivery)
    builder.save(output/'public-source-credits.json', credits)
    builder.save(output/'purpose-decisions.json', {'native': native_decisions, 'selected_inputs': decisions})
    builder.save(output/'report.json', report)
    (output/'index.html').write_text(html, encoding='utf-8')
    check_unchanged(pins)
    builder.save(output/'manifest.json', {'version': 'full-world-pilot-withdrawal-v1', 'source_sha256': pins,
        'adapter_sha256': sha(__file__), 'original_builder_sha256': BUILDER_SHA,
        'prior_delivery_manifest_sha256': sha(prior_manifest_path),
        'output_sha256': {p.name: sha(p) for p in output.iterdir()}, 'actual_model_calls': 0,
        'private_profile_used': False, 'source_artifacts_unchanged': True})
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for flag in ('runtime-root','database','ledger','selected-inputs','prior-delivery','output'):
        parser.add_argument('--'+flag, type=Path, required=True)
    parser.add_argument('--ledger-sha256', required=True)
    print(json.dumps(build(parser.parse_args()), ensure_ascii=False))
